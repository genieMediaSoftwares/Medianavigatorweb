import { Router } from 'express';
import { adminController as c } from '../controllers/admin.controller.js';
import { validate } from '../middleware/validate.js';
import { authenticate } from '../middleware/auth.js';
import { requirePermission as permit } from '../middleware/requirePermission.js';
import { permissionCatalogue } from '../services/permissions.js';
import { adminLimiter } from '../middleware/rateLimit.js';
import { requireRecentAuth, requireStaffMfa } from '../middleware/stepUp.js';
import { admin as v } from '../validators/index.js';
import { adminMonitoring } from '../services/adminMonitoring.service.js';
import { asyncHandler } from '../lib/asyncHandler.js';
import { ok } from '../lib/response.js';

export const adminRouter = Router();
// Order: valid session, then (when enforced) staff MFA enrolment, then the route's named permission, then step-up.
adminRouter.use(adminLimiter, authenticate, requireStaffMfa);
adminRouter.get('/monitoring', permit('monitoring.view'), asyncHandler(async (_req, res) => ok(res, await adminMonitoring.monitoring())));
adminRouter.get('/errors', permit('errors.view'), asyncHandler(async (_req, res) => ok(res, await adminMonitoring.errors())));
adminRouter.get('/permissions', permit('permissions.view'), asyncHandler(async (_req, res) => ok(res, permissionCatalogue())));
adminRouter.get('/system', permit('system.view'), c.system);
adminRouter.get('/users', permit('users.view'), validate({ query: v.users }), c.users);
adminRouter.get('/users/:id', permit('users.view'), validate({ params: v.idParams }), c.user);
adminRouter.patch('/users/:id/role', permit('roles.manage'), requireRecentAuth, validate({ params: v.idParams, body: v.role }), c.setRole);
adminRouter.post('/users/:id/mfa/reset', permit('roles.manage'), requireRecentAuth, validate({ params: v.idParams }), c.resetMfa);
adminRouter.patch('/users/:id/status', permit('users.suspend'), requireRecentAuth, validate({ params: v.idParams, body: v.status }), c.setStatus);
adminRouter.get('/users/:id/credit-ledger', permit('credits.view'), validate({ params: v.idParams, query: v.ledger }), c.creditLedger);
adminRouter.patch('/users/:id/credits', permit('credits.adjust'), requireRecentAuth, validate({ params: v.idParams, body: v.credits }), c.adjustCredits);
adminRouter.get('/connections', permit('connections.view'), validate({ query: v.connections }), c.connections);
adminRouter.post('/connections/:id/sync', permit('connections.sync'), validate({ params: v.idParams }), c.triggerSync);
adminRouter.get('/sync-runs', permit('syncruns.view'), validate({ query: v.syncRuns }), c.syncRuns);
adminRouter.get('/audit-logs', permit('audit.view'), validate({ query: v.audit }), c.audit);
